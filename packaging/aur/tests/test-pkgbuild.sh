#!/usr/bin/env bash
# Static checks on the AUR recipe: valid bash, required fields, and the two
# normalisations package() must perform. Runs on any host — the real build is
# packaging/aur/tests/test-aur-build.sh, which needs amd64 Linux + Docker.
set -euo pipefail

AUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
REPO_ROOT=$(cd "$AUR_DIR/../.." && pwd)
PKGBUILD="$AUR_DIR/PKGBUILD"
CONF="$REPO_ROOT/src-tauri/tauri.conf.json"
SRCINFO="$AUR_DIR/.SRCINFO"

[ -f "$PKGBUILD" ] || { echo "FAIL: no PKGBUILD at $PKGBUILD"; exit 1; }
[ -f "$CONF" ]     || { echo "FAIL: no tauri.conf.json at $CONF"; exit 1; }

bash -n "$PKGBUILD" || { echo "FAIL: PKGBUILD is not valid bash"; exit 1; }

# shellcheck disable=SC1090
source "$PKGBUILD"

fail=0
note() { echo "FAIL: $1"; fail=1; }

[ "${pkgname:-}" = "kokos-bin" ] || note "pkgname is '${pkgname:-}', expected kokos-bin"
# A repair push at an unchanged app version needs pkgrel bumped by hand —
# pin the shape, not a fixed value, so that stays legal.
case "${pkgrel:-}" in
  ''|*[!0-9]*) note "pkgrel is '${pkgrel:-}', expected a positive integer" ;;
  0)           note "pkgrel is 0, expected a positive integer" ;;
esac
[ "${arch[*]:-}" = "x86_64" ]    || note "arch is '${arch[*]:-}', expected exactly x86_64"

case " ${depends[*]:-} " in *" webkit2gtk-4.1 "*) ;; *) note "depends lacks webkit2gtk-4.1" ;; esac
case " ${depends[*]:-} " in *" gtk3 "*)           ;; *) note "depends lacks gtk3" ;; esac
case " ${provides[*]:-} " in *" kokos "*)         ;; *) note "provides lacks kokos" ;; esac
case " ${conflicts[*]:-} " in *" kokos "*)        ;; *) note "conflicts lacks kokos" ;; esac
case " ${options[*]:-} " in *" !strip "*)         ;; *) note "options lacks !strip" ;; esac

# The version must not drift from the app's own source of truth.
conf_ver=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["version"])' "$CONF")
[ "${pkgver:-}" = "$conf_ver" ] || note "pkgver '${pkgver:-}' != tauri.conf.json '$conf_ver'"

# A binary package with no checksum gives the user no integrity check at all.
sum="${sha256sums[0]:-}"
[ "$sum" != "SKIP" ] || note "sha256sums is SKIP"
[ "${#sum}" -eq 64 ] || note "sha256sums[0] is not a 64-hex digest: '$sum'"

# The source is renamed to a stable local name, so package() and noextract
# never depend on how upstream cased the filename.
local_name="kokos-${pkgver}.deb"
case "${source[0]:-}" in
  "$local_name::https://packages.kuksov.dev/deb/pool/main/k/kokos/"*) ;;
  *) note "source[0] is not '$local_name::<R2 pool URL>': '${source[0]:-}'" ;;
esac
[ "${noextract[0]:-}" = "$local_name" ] || note "noextract[0] is '${noextract[0]:-}', expected $local_name"

# makepkg would otherwise extract the .deb by mimetype guess; we unpack by hand.
body=$(declare -f package || true)
case "$body" in *"usr/bin/kokos"*) ;; *) note "package() never guarantees /usr/bin/kokos" ;; esac
case "$body" in *"licenses/"*)     ;; *) note "package() never installs a licence" ;; esac

# .SRCINFO is regenerated by prepare-release.sh, never hand-edited, but nothing
# else in this repo reads it back to confirm the two stayed in sync — AUR's own
# push hook checks .SRCINFO against itself, never against PKGBUILD. A stale
# .SRCINFO is accepted by AUR and just stops existing users
# from being offered the update, so this is the only gate that
# would ever catch a forgotten prepare-release.sh re-run before a push.
srcinfo_field() {   # srcinfo_field <key> — every matching value, joined with a
                     # single space, the same way bash joins "${arr[*]}", so a
                     # scalar and an array field compare like for like.
  local key="$1"
  sed -n -E "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*(.*)\$/\1/p" "$SRCINFO" | paste -sd' ' -
}

check_srcinfo_field() {   # check_srcinfo_field <key> <PKGBUILD value>
  local key="$1" pk_val="$2" si_val
  si_val=$(srcinfo_field "$key")
  [ "$si_val" = "$pk_val" ] || note ".SRCINFO $key ('$si_val') disagrees with PKGBUILD ('$pk_val') — regenerate .SRCINFO"
}

if [ -f "$SRCINFO" ]; then
  check_srcinfo_field pkgver     "${pkgver:-}"
  check_srcinfo_field pkgrel     "${pkgrel:-}"
  check_srcinfo_field source     "${source[*]:-}"
  check_srcinfo_field sha256sums "${sha256sums[*]:-}"
  check_srcinfo_field noextract  "${noextract[*]:-}"
else
  note ".SRCINFO is missing at $SRCINFO — it is half of what gets pushed to AUR"
fi

[ "$fail" -eq 0 ] && echo "PASS: PKGBUILD static checks"
exit "$fail"
