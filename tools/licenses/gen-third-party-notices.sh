#!/usr/bin/env bash
# Regenerate THIRD-PARTY-NOTICES.md from the Rust and npm dependency graphs.
#
# Run from anywhere; paths are resolved against the repository root.
# Prerequisites:
#   cargo install --locked cargo-about --features cli
#     (0.9.x gates the cargo-about *binary* behind the `cli` feature, which is
#     off by default; `cargo install --locked cargo-about` alone builds but
#     installs nothing, silently.)
#   npm i -g license-checker-rseidelsohn      (or use the npx form below)
set -euo pipefail

root=$(git rev-parse --show-toplevel)
cd "$root"
out="$root/THIRD-PARTY-NOTICES.md"
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

command -v cargo-about >/dev/null 2>&1 || {
  echo "cargo-about is missing: cargo install --locked cargo-about --features cli" >&2
  exit 1
}

{
  echo "# Third-Party Notices"
  echo
  echo "Kokos incorporates the third-party components listed below. Each is"
  echo "distributed under its own licence, reproduced in full. These licences"
  echo "govern those components only; Kokos itself is licensed under the"
  echo "MIT License (see \`LICENSE\`)."
  echo
  echo "This file is generated by \`tools/licenses/gen-third-party-notices.sh\`."
  echo "Do not edit it by hand."
  echo
} > "$tmp"

cargo about generate \
  --config tools/licenses/about.toml \
  tools/licenses/about.hbs >> "$tmp"

{
  echo
  echo "## Frontend dependencies"
  echo
  echo '````'
} >> "$tmp"

# --production excludes devDependencies, which are build-time only and do not
# ship inside the application bundle. --excludePrivatePackages drops our own
# root package (package.json has "private": true) -- without it, this walk
# lists "kokos" itself as if it were a third-party dependency and dumps our
# own licence text into a file whose header promises third-party-only
# content. This is the npm-side equivalent of about.toml's private.ignore.
#
# --excludePackages '@tauri-apps/api': that package ships its licence text as
# LICENSE_APACHE-2.0 / LICENSE_MIT, filenames license-checker-rseidelsohn's
# built-in detection patterns (LICENSE, LICENSE-<word>, COPYING, ...) do not
# match, so with no override it falls back to its last-resort heuristic and
# bundles the package README instead -- badges, install instructions, no
# licence text at all. Excluded here and reproduced explicitly below, from the
# package's own files, so the notice for it is real instead of a README dump.
#
# The whole scan is wrapped in a fenced code block (four backticks: tauri's
# own README -- the exact thing being excluded, but other packages can hit the
# same README-fallback and stay in this scan -- may itself contain a
# triple-backtick snippet that would close a triple-backtick fence early).
# Unlike the Rust section, where about.hbs fences each licence individually,
# this is raw upstream text, READMEs included whenever a package has no
# licence file the scanner recognises, and a stray Markdown heading or an
# <img> tag in one would otherwise restructure this document.
npx --yes license-checker-rseidelsohn \
  --production \
  --excludePrivatePackages \
  --excludePackages '@tauri-apps/api' \
  --plainVertical \
  --relativeLicensePath >> "$tmp"

{
  echo
  echo '````'
} >> "$tmp"

# Explicit correction for @tauri-apps/api (see the exclusion comment above):
# its real licence texts, read directly from the installed package, the same
# way the vendored keepass section below is handled.
tauri_dir="node_modules/@tauri-apps/api"
tauri_version=$(node -p "require('./$tauri_dir/package.json').version" 2>/dev/null || echo "unknown")
{
  echo
  echo "### @tauri-apps/api $tauri_version"
  echo
  echo "Declared licence (\`package.json\`): Apache-2.0 OR MIT. Reproduced here"
  echo "directly from the installed package -- see the exclusion comment above"
  echo "for why the automated scan can't find it."
  echo
  echo '```'
} >> "$tmp"
cat "$tauri_dir/LICENSE_APACHE-2.0" >> "$tmp" 2>/dev/null || \
  echo "(LICENSE_APACHE-2.0 not found in $tauri_dir — investigate)" >> "$tmp"
{
  echo '```'
  echo
  echo '```'
} >> "$tmp"
cat "$tauri_dir/LICENSE_MIT" >> "$tmp" 2>/dev/null || \
  echo "(LICENSE_MIT not found in $tauri_dir — investigate)" >> "$tmp"
echo '```' >> "$tmp"

# The vendored crate under vendor/ is a patched third-party dependency and is
# not part of the cargo registry graph cargo-about walks. Append it explicitly.
{
  echo
  echo "## Vendored components"
  echo
  echo "### vendor/keepass-0.8.7"
  echo
  echo "A patched copy of the \`keepass\` crate, used for KDBX import."
  echo
  echo '```'
} >> "$tmp"
cat vendor/keepass-0.8.7/LICENSE* >> "$tmp" 2>/dev/null || \
  echo "(licence file not found in vendor/keepass-0.8.7 — investigate)" >> "$tmp"
echo '```' >> "$tmp"

# The bundled fonts are copied into src/assets/fonts rather than installed
# from npm, so neither scan above sees them. Append their licence explicitly.
{
  echo
  echo "## Bundled fonts"
  echo
  echo "### Geist and Geist Mono"
  echo
  echo "Variable fonts in \`src/assets/fonts\`, used for the app's interface text."
  echo
  echo '```'
} >> "$tmp"
cat src/assets/fonts/OFL.txt >> "$tmp" 2>/dev/null || \
  echo "(OFL.txt not found in src/assets/fonts — investigate)" >> "$tmp"
echo '```' >> "$tmp"

# mktemp creates $tmp 0600 and mv preserves that mode on rename -- without
# this, a release cut on a machine that just regenerated this file ships an
# unreadable /usr/share/doc/kokos/THIRD-PARTY-NOTICES.md.
chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
